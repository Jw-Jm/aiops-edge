type fakeRegistrationStore struct {
	clusters  map[string]*store.Cluster // by ClusterID
	byUID     map[string]*store.Cluster // by KubernetesIdentityUID
	registerErr error
}

func (f *fakeRegistrationStore) RegisterCluster(c *store.Cluster) error {
	if f.registerErr != nil {
		return f.registerErr
	}
	// Mirror the production duplicate-active guard.
	if existing, ok := f.byUID[c.KubernetesIdentityUID]; ok && existing.ClusterID != c.ClusterID {
		return store.ErrClusterIdentityDuplicate
	}
	f.clusters[c.ClusterID] = c
	f.byUID[c.KubernetesIdentityUID] = c
	return nil
}

func (f *fakeRegistrationStore) FindActiveByKubeSystemUID(uid string) (*store.Cluster, error) {
	c, ok := f.byUID[uid]
	if !ok {
		return nil, nil
	}
	return c, nil
}

func TestClusterRegistrarDiscoversIdentityFromTargetCluster(t *testing.T) {
	kcreader := &fakeKubeconfigReader{kcByRef: map[string]string{secretA: kcA}}
	ireader := &fakeIdentityReader{uidByKubeconfig: map[string]string{kcA: uidA}}
	dao := &fakeRegistrationStore{clusters: map[string]*store.Cluster{}, byUID: map[string]*store.Cluster{}}

	r := NewClusterRegistrar(kcreader, ireader, dao)
	got, err := r.Register(ClusterRegistration{
		TenantID:      "33333333-3333-4333-8333-333333333333",
		Slug:          "orbstack",
		Name:          "Orbstack",
		Environment:   "prod",
		Region:        "cn-shanghai",
		CredentialRef: secretA,
	})
	if err != nil {
		t.Fatalf("Register() error = %v", err)
	}
	// The persisted identity MUST be the one discovered from the target cluster,
	// NOT anything a caller could have supplied (ClusterRegistration has no UID).
	if got.KubernetesIdentityUID != uidA {
		t.Fatalf("persisted identity = %q, want discovered uidA %q", got.KubernetesIdentityUID, uidA)
	}
	if !canonicalUUID.MatchString(got.ClusterID) {
		t.Fatalf("generated cluster_id = %q is not canonical", got.ClusterID)
	}
	if got.KubernetesIdentityUID == got.ClusterID {
		t.Fatalf("cluster_id must never equal kube-system UID")
	}
	// The canonical UUID was generated by the registrar, not derived from the UID.
	if got.ClusterID == uidA {
		t.Fatalf("cluster_id must be independently generated")
	}
}

func TestClusterRegistrarRejectsWhenCredentialUnresolvable(t *testing.T) {
	kcreader := &fakeKubeconfigReader{kcByRef: map[string]string{}, errByRef: map[string]error{secretA: errSecretNotFound}}
	ireader := &fakeIdentityReader{}
	dao := &fakeRegistrationStore{clusters: map[string]*store.Cluster{}, byUID: map[string]*store.Cluster{}}

	r := NewClusterRegistrar(kcreader, ireader, dao)
	_, err := r.Register(ClusterRegistration{TenantID: "33333333-3333-4333-8333-333333333333", CredentialRef: secretA})
	if err == nil {
		t.Fatal("Register(unresolvable credential) error = nil, want fail")
	}
	if len(dao.clusters) != 0 {
		t.Fatalf("Register(unresolvable credential) wrote %d rows, want 0 (no partial registration)", len(dao.clusters))
	}
}

