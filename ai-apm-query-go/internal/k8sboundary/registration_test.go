func TestClusterRegistrarRejectsDuplicateActivePhysicalCluster(t *testing.T) {
	kcreader := &fakeKubeconfigReader{kcByRef: map[string]string{secretA: kcA, secretB: kcB}}
	ireader := &fakeIdentityReader{uidByKubeconfig: map[string]string{kcA: uidA, kcB: uidB}}
	dao := &fakeRegistrationStore{
		clusters: map[string]*store.Cluster{},
		byUID: map[string]*store.Cluster{
			uidA: {ClusterID: uuidA, KubernetesIdentityUID: uidA},
		},
	}

	r := NewClusterRegistrar(kcreader, ireader, dao)

	// A credential resolving to uidA while uidA is already active must be rejected:
	// the same physical Kubernetes cluster cannot be active under two canonical UUIDs.
	kcA2 := "kubeconfig-A2"
	ireader.uidByKubeconfig[kcA2] = uidA
	kcreader.kcByRef["k8s-secret://aiops/cluster-a2"] = kcA2
	_, err := r.Register(ClusterRegistration{TenantID: "33333333-3333-4333-8333-333333333333", Slug: "orbstack-dup", CredentialRef: "k8s-secret://aiops/cluster-a2"})
	if !errors.Is(err, store.ErrClusterIdentityDuplicate) {
		t.Fatalf("Register(duplicate active physical cluster) error = %v, want ErrClusterIdentityDuplicate", err)
	}
}

func TestNewCanonicalUUIDIsCanonicalAndLowercase(t *testing.T) {
	for i := 0; i < 50; i++ {
		id, err := newCanonicalUUID()
		if err != nil {
			t.Fatalf("newCanonicalUUID() error = %v", err)
		}
		if !canonicalUUID.MatchString(id) {
			t.Fatalf("newCanonicalUUID() = %q does not match canonical pattern", id)
		}
		if strings.ToLower(id) != id {
			t.Fatalf("newCanonicalUUID() = %q is not lowercase", id)
		}
	}
}
